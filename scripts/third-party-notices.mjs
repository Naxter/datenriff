#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.md from what a built site actually bundles.
//
// The repository vendors no dependencies — node_modules is git-ignored — so
// this is about the deployed site, not the repo. Minified bundles drop every
// legal comment, and MIT, BSD and ISC all require their copyright notice to
// travel with copies. This file is where it travels.
//
//   node scripts/third-party-notices.mjs
//
// Walks the production dependency closure of apps/web in the installed tree,
// takes each package's own copyright line out of its licence file, and quotes
// the full text of every distinct licence once.

import { readFileSync, existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'THIRD-PARTY-NOTICES.md');
/** Our own workspace packages: covered by this repository's LICENSE. */
const OURS = /^@datenriff\//;

const pkgDir = (name) => {
  for (const base of ['apps/web/node_modules', 'node_modules']) {
    const p = join(ROOT, base, name, 'package.json');
    if (existsSync(p)) return dirname(p);
  }
  return null;
};

/** Every production dependency reachable from apps/web. */
function closure() {
  const seen = new Map();
  const visit = (name) => {
    if (seen.has(name)) return;
    const dir = pkgDir(name);
    if (!dir) return; // an optional or platform-specific dep that is not installed
    const doc = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    seen.set(name, {
      version: doc.version,
      license: doc.license ?? doc.licenses?.[0]?.type ?? 'UNKNOWN',
      dir,
    });
    for (const dep of Object.keys(doc.dependencies ?? {})) visit(dep);
  };
  const root = JSON.parse(readFileSync(join(ROOT, 'apps/web/package.json'), 'utf8'));
  for (const dep of Object.keys(root.dependencies ?? {})) visit(dep);
  return [...seen.entries()]
    .filter(([name]) => !OURS.test(name))
    .sort(([a], [b]) => a.localeCompare(b));
}

/** A package's licence file, and the copyright line inside it. */
function licenceFile(dir) {
  for (const f of readdirSync(dir)) {
    if (!/^(LICEN[CS]E|COPYING)/i.test(f)) continue;
    const p = join(dir, f);
    if (statSync(p).isFile()) return readFileSync(p, 'utf8');
  }
  return null;
}

const copyrightOf = (text) =>
  text
    ?.split(/\r?\n/)
    .find((l) => /copyright/i.test(l) && !/\[yyyy\]/.test(l))
    ?.trim()
    .replace(/^[#*/\s]+/, '') ?? null;

/** A package's own NOTICE, if it has one.
 *
 *  Apache-2.0 §4(d) is the one clause a licence-name-and-copyright summary
 *  does not satisfy: a NOTICE file shipped with a dependency has to travel
 *  with every distribution of a work that includes it. `apache-arrow` ships
 *  one and it was being dropped. */
function noticeFile(dir) {
  for (const f of readdirSync(dir)) {
    if (!/^NOTICE(\.|$)/i.test(f)) continue;
    const p = join(dir, f);
    if (statSync(p).isFile()) return readFileSync(p, 'utf8').trim();
  }
  return null;
}

const packages = closure();
const missing = packages.filter(([, v]) => !copyrightOf(licenceFile(v.dir)));

// One full licence text per distinct licence, taken from a package that uses it
const texts = new Map();
for (const [, v] of packages) {
  if (texts.has(v.license)) continue;
  const text = licenceFile(v.dir);
  if (text) texts.set(v.license, text.trim());
}

const lines = [
  '# Third-party notices',
  '',
  'Datenriff bundles the libraries below into the site it builds. Their',
  "licences require their copyright notices to travel with copies, and a",
  'minified bundle keeps none of them — so they are reproduced here.',
  '',
  'This file is generated by `scripts/third-party-notices.mjs` from the',
  'installed dependency tree. Regenerate it after changing dependencies.',
  '',
  "The repository's own code is licensed separately; see `LICENSE` and",
  '`NOTICE`. Data produced by the pipelines is covered by neither — see',
  '`NOTICE`.',
  '',
  `## Packages (${packages.length})`,
  '',
  '| Package | Version | Licence | Copyright |',
  '| --- | --- | --- | --- |',
];
for (const [name, v] of packages) {
  const c = copyrightOf(licenceFile(v.dir)) ?? '—';
  lines.push(`| \`${name}\` | ${v.version} | ${v.license} | ${c.replace(/\|/g, '\\|')} |`);
}
// Upstream NOTICE files, reproduced whole. Apache-2.0 §4(d) requires it and
// no summary substitutes for it.
const notices = packages
  .map(([name, v]) => [name, noticeFile(v.dir)])
  .filter(([, text]) => text);
if (notices.length) {
  lines.push(
    '',
    `## Upstream NOTICE files (${notices.length})`,
    '',
    'Apache-2.0 §4(d) requires a dependency\'s own NOTICE to travel with every',
    'distribution that includes it. These are reproduced verbatim.',
    '',
  );
  for (const [name, text] of notices) {
    lines.push(`### ${name}`, '', '```', text, '```', '');
  }
}

lines.push('', '## Licence texts', '');
for (const [license, text] of [...texts].sort()) {
  lines.push(`### ${license}`, '', '```', text, '```', '');
}

writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
console.log(
  `wrote THIRD-PARTY-NOTICES.md — ${packages.length} packages, ${texts.size} licences,` +
    ` ${notices.length} upstream NOTICE file(s)`,
);
if (missing.length) {
  console.warn(`no copyright line found for: ${missing.map(([n]) => n).join(', ')}`);
}
